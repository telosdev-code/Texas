/**
 * Generates src/core/data/preflopEquity.ts: each hand class's equity against one uniformly random hand.
 * Monte Carlo estimate (labelled as such in the UI). Run: npm run gen:preflop
 */
import { writeFileSync } from 'node:fs';
import { computeEquity } from '../src/core/equity.ts';
import { combosOfClass, fullRange, HAND_CLASSES, rangeToCombos } from '../src/core/ranges.ts';

const SAMPLES = 60_000;
const rows: number[] = [];
for (const h of HAND_CLASSES) {
  const cards = combosOfClass(h)[0];
  const r = computeEquity({
    players: [{ kind: 'hand', cards }, { kind: 'range', combos: rangeToCombos(fullRange(), cards) }],
    method: 'monte-carlo',
    samples: SAMPLES,
    seed: 1000 + h.index,
  });
  rows.push(Math.round(r.equity[0] * 10000) / 10000);
}
const out = `// Generated by scripts/gen-preflop-equity.ts — do not edit by hand.
// Equity of each hand class (matrix index order) vs. one uniformly random hand.
// Monte Carlo estimate: ${SAMPLES.toLocaleString('en-US')} samples per class (standard error ≤ 0.21 percentage points).
export const PREFLOP_EQUITY_SAMPLES = ${SAMPLES};
export const PREFLOP_EQUITY_VS_RANDOM: readonly number[] = [
${rows.map((v) => v.toFixed(4)).join(', ').replace(/((?:[^,]*, ){13})/g, '$1\n')}
];
`;
writeFileSync(new URL('../src/core/data/preflopEquity.ts', import.meta.url), out);
console.log('AA', rows[0], '72o', rows[HAND_CLASSES.find((h) => h.label === '72o')!.index]);
